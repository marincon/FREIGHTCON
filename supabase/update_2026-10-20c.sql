-- ---------- structure ----------
create table if not exists public.rate_tables (
  id                     text primary key,
  name                   text not null,
  mode                   text not null check (mode in ('sea','air')),
  zones                  int  not null,
  war_included_permille  numeric(8,4) not null default 0,   -- war & strikes already inside the matrix rates
  min_premium            numeric(12,2) not null default 100,
  deck_allowed           boolean not null default false,     -- on-deck shipment can be priced (with deck loading)
  contingency_allowed    boolean not null default false,     -- seller's / buyer's interest can be priced
  used_loading_pct       numeric(6,2),                       -- air: loading for used goods
  cars_loading_pct       numeric(6,2),                       -- air: loading for cars / motorcycles
  household_flat_permille numeric(8,4),                      -- air: flat rate for household goods (null = on request)
  notes                  text,
  sort                   int not null default 100,
  updated_at             timestamptz not null default now()
);
create table if not exists public.rate_cells (
  table_id  text not null references public.rate_tables(id) on delete cascade,
  zone_a    int  not null check (zone_a >= 1),
  zone_b    int  not null check (zone_b >= zone_a),
  permille  numeric(8,4) not null check (permille >= 0),
  primary key (table_id, zone_a, zone_b)
);
alter table public.rate_tables enable row level security;
alter table public.rate_cells  enable row level security;
drop policy if exists admin_all on public.rate_tables;
create policy admin_all on public.rate_tables for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists admin_all on public.rate_cells;
create policy admin_all on public.rate_cells for all to authenticated using (public.is_admin()) with check (public.is_admin());

